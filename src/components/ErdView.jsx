// Read-only entity-relationship view of a relational schema's diagram, in
// crow's foot notation (workbench step 6). The tables, columns and keys come
// from relationalModel (the same reading the DDL export uses); a diagram shows
// the tables whose entity type it shows. Box positions are kept per diagram in
// diagram.erdPositions (top-left corners); tables without one are laid out in a
// grid. A click selects the table (header) or the column (row) for the
// Inspector; dragging a box moves it, as one undo step.

import React, { useMemo, useState, useRef, useEffect } from 'react'
import { useOrmStore } from '../store/ormStore'
import { inDiag } from '../store/storeHelpers'
import { relationalModel, isKey } from '../relational/relationalModel'
import { typeSql } from '../relational/ddlExport'

const FONT = "'Segoe UI', Helvetica, Arial, sans-serif"
const HEAD_H = 24, ROW_H = 19, PAD_X = 8, MARK_GAP = 6, GAP_TYPE = 18, MIN_W = 140
const GRID_GAP_X = 90, GRID_GAP_Y = 70

// Whether the diagram is drawn as an ERD: its schema is relational and the
// notation switch is on.
export function isErdDiagram(state, diagram) {
  if (diagram?.notation !== 'erd') return false
  return state.schemas?.find(s => s.id === diagram.schemaId)?.profile === 'relational'
}

let _canvas = null
function measure(text, size, weight = 400) {
  if (!_canvas) _canvas = document.createElement('canvas')
  const ctx = _canvas.getContext('2d')
  ctx.font = `${weight} ${size}px ${FONT}`
  return ctx.measureText(text).width
}

function columnType(col) {
  const t = typeSql(col.vt.datatypeAssignment, col.generated)
  if (!t) return col.vt.name
  return t.replace(' generated by default as identity', ' identity')
}

function columnMarks(col) {
  return [col.pk && 'PK', col.fk && 'FK', !col.pk && col.unique && 'U'].filter(Boolean).join(' ')
}

// Box sizes, and positions for tables that have none stored: a grid in an
// order that keeps tables joined by foreign keys close together.
export function erdLayout(model, diagram) {
  const shown = model.tables.filter(t => inDiag(diagram, t.id))
  const boxes = new Map()
  for (const t of shown) {
    // Width of the PK/FK/U column: the widest marks in this table.
    const markW = Math.max(16, ...t.columns.map(c => measure(columnMarks(c), 9, 700))) + MARK_GAP
    let w = measure(t.name, 13, 700) + PAD_X * 2
    for (const c of t.columns)
      w = Math.max(w, markW + measure(c.name, 12, c.notNull ? 600 : 400) + GAP_TYPE + measure(columnType(c), 11) + PAD_X * 2)
    boxes.set(t.id, { table: t, markW, w: Math.ceil(Math.max(MIN_W, w)), h: HEAD_H + Math.max(1, t.columns.length) * ROW_H + 6 })
  }
  const stored = diagram.erdPositions ?? {}
  const missing = shown.filter(t => !stored[t.id])
  let originY = 0
  for (const t of shown) {
    const p = stored[t.id]
    if (p) { boxes.get(t.id).x = p.x; boxes.get(t.id).y = p.y; originY = Math.max(originY, p.y + boxes.get(t.id).h + GRID_GAP_Y) }
  }
  if (missing.length) {
    // Breadth-first over foreign keys, starting from the most connected table.
    const nbrs = new Map(missing.map(t => [t.id, new Set()]))
    for (const fk of model.fks) {
      if (fk.fromTable === fk.toTable) continue
      nbrs.get(fk.fromTable.id)?.add(fk.toTable.id)
      nbrs.get(fk.toTable.id)?.add(fk.fromTable.id)
    }
    const order = []
    const seen = new Set()
    const byDegree = [...missing].sort((a, b) => nbrs.get(b.id).size - nbrs.get(a.id).size)
    for (const start of byDegree) {
      if (seen.has(start.id)) continue
      const queue = [start.id]
      seen.add(start.id)
      while (queue.length) {
        const id = queue.shift()
        order.push(id)
        const next = [...nbrs.get(id)].filter(n => !seen.has(n)).sort((a, b) => nbrs.get(b).size - nbrs.get(a).size)
        for (const n of next) { seen.add(n); queue.push(n) }
      }
    }
    const cols = Math.max(1, Math.ceil(Math.sqrt(order.length * 1.6)))
    const colW = [], rowH = []
    order.forEach((id, i) => {
      const b = boxes.get(id), c = i % cols, r = Math.floor(i / cols)
      colW[c] = Math.max(colW[c] ?? 0, b.w)
      rowH[r] = Math.max(rowH[r] ?? 0, b.h)
    })
    order.forEach((id, i) => {
      const b = boxes.get(id), c = i % cols, r = Math.floor(i / cols)
      let x = 0, y = originY
      for (let k = 0; k < c; k++) x += colW[k] + GRID_GAP_X
      for (let k = 0; k < r; k++) y += rowH[k] + GRID_GAP_Y
      b.x = x; b.y = y
    })
  }
  return boxes
}

// y of a column's row centre inside its box.
const rowY = (box, col) => box.y + HEAD_H + 3 + Math.max(0, box.table.columns.indexOf(col)) * ROW_H + ROW_H / 2

// Crow's foot end marker at point p on a box side; d is +1 when the line
// leaves to the right, -1 to the left. kind: 'one' (||), 'zeroOne' (o|),
// 'zeroMany' (o<).
function EndMarker({ x, y, d, kind }) {
  const stroke = 'var(--ink-2)'
  const bar = (at) => <line x1={x + d * at} y1={y - 6} x2={x + d * at} y2={y + 6} stroke={stroke} strokeWidth={1.3}/>
  const circle = (at) => <circle cx={x + d * at} cy={y} r={3.8} fill="var(--bg-canvas)" stroke={stroke} strokeWidth={1.3}/>
  if (kind === 'one') return <g>{bar(9)}{bar(14)}</g>
  if (kind === 'zeroOne') return <g>{bar(9)}{circle(19)}</g>
  return (
    <g>
      <path d={`M ${x} ${y - 7} L ${x + d * 12} ${y} L ${x} ${y + 7} M ${x} ${y} L ${x + d * 12} ${y}`}
        fill="none" stroke={stroke} strokeWidth={1.3}/>
      {circle(18)}
    </g>
  )
}

const LEAD = 24  // straight part before a curve, so the markers sit on it

function FkLine({ fk, boxes }) {
  const a = boxes.get(fk.fromTable.id), b = boxes.get(fk.toTable.id)
  if (!a || !b) return null
  const y1 = rowY(a, fk.from[0]), y2 = rowY(b, fk.to[0])
  let x1, d1, x2, d2
  if (a === b) { x1 = a.x + a.w; d1 = 1; x2 = b.x + b.w; d2 = 1 }
  else if (b.x > a.x + a.w) { x1 = a.x + a.w; d1 = 1; x2 = b.x; d2 = -1 }
  else if (b.x + b.w < a.x) { x1 = a.x; d1 = -1; x2 = b.x + b.w; d2 = 1 }
  else {
    // Overlapping horizontally: leave and enter on the right.
    x1 = a.x + a.w; d1 = 1; x2 = b.x + b.w; d2 = 1
  }
  const bend = a === b || d1 === d2 ? Math.max(40, Math.abs(x2 - x1) / 2 + 40) : Math.max(30, Math.abs(x2 - x1) / 3)
  const p1x = x1 + d1 * LEAD, p2x = x2 + d2 * LEAD
  const c1x = d1 === d2 ? Math.max(p1x, p2x) + bend * 0.6 : p1x + d1 * bend
  const c2x = d1 === d2 ? Math.max(p1x, p2x) + bend * 0.6 : p2x + d2 * bend
  const path = `M ${x1} ${y1} L ${p1x} ${y1} C ${c1x} ${y1}, ${c2x} ${y2}, ${p2x} ${y2} L ${x2} ${y2}`
  const nullable = fk.from.some(c => !c.notNull)
  const many = !isKey(fk.fromTable, fk.from)
  return (
    <g>
      <path d={path} fill="none" stroke="var(--ink-2)" strokeWidth={1.3} strokeDasharray={nullable ? '5 3' : undefined}/>
      <EndMarker x={x1} y={y1} d={d1} kind={many ? 'zeroMany' : 'zeroOne'}/>
      <EndMarker x={x2} y={y2} d={d2} kind={nullable ? 'zeroOne' : 'one'}/>
    </g>
  )
}

function TableBox({ box, selectedId, onHeaderDown, onRowDown }) {
  const { table: t, x, y, w, h } = box
  const sel = selectedId === t.id
  const head = 'var(--col-schema-relational)'
  return (
    <g style={{ fontFamily: FONT }}>
      <rect x={x} y={y} width={w} height={h} rx={4} fill="var(--bg-text-panel)"
        stroke={sel ? 'var(--accent)' : 'var(--border-dark)'} strokeWidth={sel ? 2.2 : 1.2}
        filter={sel ? 'url(#selectGlow)' : undefined}/>
      <g onMouseDown={e => onHeaderDown(e, t)} style={{ cursor: 'move' }}>
        <path d={`M ${x} ${y + HEAD_H} L ${x} ${y + 4} Q ${x} ${y} ${x + 4} ${y} L ${x + w - 4} ${y} Q ${x + w} ${y} ${x + w} ${y + 4} L ${x + w} ${y + HEAD_H} Z`}
          fill={head}/>
        <text x={x + PAD_X} y={y + HEAD_H / 2 + 4.5} fontSize={13} fontWeight={700} fill="#fff"
          style={{ userSelect: 'none', pointerEvents: 'none' }}>{t.name}</text>
      </g>
      {t.columns.map((c, i) => {
        const ry = y + HEAD_H + 3 + i * ROW_H
        const csel = selectedId === c.fact.id
        return (
          <g key={c.fact.id} onMouseDown={e => onRowDown(e, t, c)} style={{ cursor: 'pointer' }}>
            <rect x={x + 1} y={ry} width={w - 2} height={ROW_H} fill={csel ? 'var(--selection)' : 'transparent'}/>
            {i > 0 && t.columns[i - 1].pk && !c.pk && (
              <line x1={x + 1} y1={ry} x2={x + w - 1} y2={ry} stroke="var(--border-soft)" strokeWidth={1}/>
            )}
            <text x={x + PAD_X} y={ry + ROW_H / 2 + 3.5} fontSize={9} fontWeight={700}
              fill={c.pk ? 'var(--accent)' : 'var(--col-schema-relational)'} style={{ userSelect: 'none' }}>{columnMarks(c)}</text>
            <text x={x + PAD_X + box.markW} y={ry + ROW_H / 2 + 4} fontSize={12} fontWeight={c.notNull ? 600 : 400}
              fill="var(--ink)" textDecoration={c.pk ? 'underline' : undefined} style={{ userSelect: 'none' }}>{c.name}</text>
            <text x={x + w - PAD_X} y={ry + ROW_H / 2 + 4} fontSize={11} textAnchor="end"
              fill="var(--ink-3)" style={{ userSelect: 'none' }}>{columnType(c)}</text>
          </g>
        )
      })}
      {!t.columns.length && (
        <text x={x + PAD_X} y={y + HEAD_H + 3 + ROW_H / 2 + 4} fontSize={11} fontStyle="italic" fill="var(--ink-muted)">no columns</text>
      )}
    </g>
  )
}

export default function ErdView() {
  const objectTypes = useOrmStore(s => s.objectTypes)
  const facts       = useOrmStore(s => s.facts)
  const constraints = useOrmStore(s => s.constraints)
  const diagram     = useOrmStore(s => s.diagrams.find(d => d.id === s.activeDiagramId))
  const selectedId  = useOrmStore(s => s.selectedId)
  const schemaId    = diagram?.schemaId

  const model = useMemo(() => relationalModel({ objectTypes, facts, constraints }, schemaId),
    [objectTypes, facts, constraints, schemaId])
  const boxes = useMemo(() => diagram ? erdLayout(model, diagram) : new Map(), [model, diagram])

  // While a box is dragged its offset is local; it is stored on mouse up.
  const [drag, setDrag] = useState(null)  // { id, dx, dy }
  const dragRef = useRef(null)
  useEffect(() => () => dragRef.current?.cleanup?.(), [])

  const startDrag = (e, t) => {
    if (e.button !== 0) return
    e.stopPropagation()
    e.preventDefault()
    const store = useOrmStore.getState()
    store.select(t.id, 'entity')
    const sx = e.clientX, sy = e.clientY
    const onMove = (ev) => {
      const z = useOrmStore.getState().zoom
      const dx = (ev.clientX - sx) / z, dy = (ev.clientY - sy) / z
      if (!dragRef.current.moved && Math.hypot(dx, dy) < 3 / z) return
      dragRef.current.moved = true
      dragRef.current.dx = dx; dragRef.current.dy = dy
      setDrag({ id: t.id, dx, dy })
    }
    const cleanup = () => {
      window.removeEventListener('mousemove', onMove)
      window.removeEventListener('mouseup', onUp)
    }
    const onUp = () => {
      cleanup()
      const r = dragRef.current
      dragRef.current = null
      setDrag(null)
      if (!r?.moved) return
      // The first move fixes every shown table where it is drawn now, so the
      // grid doesn't reflow around the moved one.
      const positions = {}
      for (const [id, b] of boxes) positions[id] = { x: b.x, y: b.y }
      positions[t.id] = { x: Math.round(boxes.get(t.id).x + r.dx), y: Math.round(boxes.get(t.id).y + r.dy) }
      useOrmStore.getState().setErdPositions(diagram.id, positions)
    }
    dragRef.current = { moved: false, dx: 0, dy: 0, cleanup }
    window.addEventListener('mousemove', onMove)
    window.addEventListener('mouseup', onUp)
  }

  const selectColumn = (e, t, c) => {
    if (e.button !== 0) return
    e.stopPropagation()
    useOrmStore.getState().select(c.fact.id, 'fact')
  }

  const shown = drag
    ? new Map([...boxes].map(([id, b]) => [id, id === drag.id ? { ...b, x: b.x + drag.dx, y: b.y + drag.dy } : b]))
    : boxes

  return (
    <g className="erd-view">
      {model.fks.map(fk => <FkLine key={fk.constraintId} fk={fk} boxes={shown}/>)}
      {[...shown.values()].map(b => (
        <TableBox key={b.table.id} box={b} selectedId={selectedId} onHeaderDown={startDrag} onRowDown={selectColumn}/>
      ))}
    </g>
  )
}
