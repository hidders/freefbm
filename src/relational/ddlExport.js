// Writes a relational schema (encoding B, see ddlImport.js) as PostgreSQL DDL:
// a CREATE TABLE per table with its columns, NOT NULL, PRIMARY KEY, UNIQUE and
// CHECK (value ranges), then the foreign keys as ALTER TABLE statements, so the
// tables can be created in any order. Other constraints are written from
// their formulas (formulaSql.js): as a CHECK when they are about one row,
// otherwise as a commented query that returns their violations. What has no
// SQL form here is listed in comments at the end and returned as warnings.
// The schema itself is a relational schema in general, so whatever PostgreSQL
// can't enforce is only reported here, at export (DdlExportDialog.jsx).
//
// Assertions (constraints written as a query that returns their violations)
// are written as commented queries, or with { assertions: 'triggers' } as
// constraint triggers: a PL/pgSQL function that raises an exception when the
// query returns a row, run after each change of a table the query reads,
// deferred to the end of the transaction (deontic ones stay comments).
//
// exportPostgresDdl(state, schemaId, { assertions: 'comments'|'triggers' })
//   → { sql, warnings, queries, assertions }

import { tableRulesOf, tableRuleAsMapping } from './derivedTables.js'
import { tableViews, viewOrder } from './viewSql.js'
import { sideContext, sideTokens, tokensText } from '../mapping/mapping.js'
import { valueKindName } from '../utils/datatypeValues.js'
import { relationalModel } from './relationalModel.js'
import { quoteIdent } from './sqlNames.js'
import { constraintsAsSql } from './formulaSql.js'

export { quoteIdent }

// A constraint's name as a SQL identifier part (lower case, underscores).
const snakeName = (name) => String(name ?? '').trim().replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '').toLowerCase()

const NUMERIC_KINDS = new Set(['integer', 'decimal', 'float'])

export function typeSql(assignment, generated) {
  if (generated === 'serial' || generated === 'bigserial' || generated === 'smallserial') return generated
  if (!assignment?.datatypeId) return null
  const p = assignment.params ?? {}
  const id = assignment.datatypeId
  let out
  if (assignment.profileId === 'postgresql') {
    if (id === 'user-defined') out = p.sql || null
    else if (id === 'character varying') out = p.length ? `varchar(${p.length})` : 'varchar'
    else if (id === 'bit' || id === 'bit varying') out = p.length ? `${id}(${p.length})` : id
    else if (id === 'character') out = p.length ? `char(${p.length})` : 'char'
    else if (id === 'numeric') out = p.precision != null ? `numeric(${p.precision}${p.scale != null ? `, ${p.scale}` : ''})` : 'numeric'
    else if (id === 'time' || id === 'timestamp') out = `${id}${p.precision != null ? `(${p.precision})` : ''}${p.withTimeZone ? ' with time zone' : ''}`
    else if (id === 'interval') out = `interval${p.fields ? ` ${p.fields}` : ''}${p.precision != null ? `(${p.precision})` : ''}`
    else out = id
  } else if (assignment.profileId === 'sql2016') {
    const args = Object.entries(p).filter(([k]) => k !== 'withTimeZone').map(([, v]) => v)
    out = `${id.toLowerCase()}${args.length ? `(${args.join(', ')})` : ''}${p.withTimeZone ? ' with time zone' : ''}`
  } else return null
  if (!out) return null
  if (generated === 'identity') out += ' generated by default as identity'
  return out
}

function literalSql(value, numeric) {
  const v = String(value)
  if (numeric && /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(v.trim())) return v.trim()
  return `'${v.replace(/'/g, "''")}'`
}

// A value range as a SQL condition on col.
export function rangeSql(col, specs, numeric) {
  const lit = (v) => literalSql(v, numeric)
  const singles = specs.filter(s => s.type === 'single')
  const parts = []
  if (singles.length === 1) parts.push(`${col} = ${lit(singles[0].value)}`)
  else if (singles.length > 1) parts.push(`${col} IN (${singles.map(s => lit(s.value)).join(', ')})`)
  for (const s of specs) {
    if (s.type === 'range') parts.push(`${col} ${s.lowerOpen ? '>' : '>='} ${lit(s.lower)} AND ${col} ${s.upperOpen ? '<' : '<='} ${lit(s.upper)}`)
    else if (s.type === 'lower') parts.push(`${col} ${s.lowerOpen ? '>' : '>='} ${lit(s.lower)}`)
    else if (s.type === 'upper') parts.push(`${col} ${s.upperOpen ? '<' : '<='} ${lit(s.upper)}`)
  }
  if (!parts.length) return null
  return parts.length === 1 ? parts[0] : parts.map(p => `(${p})`).join(' OR ')
}

export function exportPostgresDdl(state, schemaId, { assertions: assertionMode = 'comments' } = {}) {
  const inSchema = (x) => !schemaId || x.schemaId === schemaId
  const model = relationalModel(state, schemaId)
  const { tables, fks, notColumns } = model
  const warnings = []
  // Constraints without a table form, written from their formulas.
  const tableById = new Map(tables.map(t => [t.id, t]))
  const queries = [], unwrittenNotes = []
  constraintsAsSql(state, model).forEach(({ c, entries }, i) => {
    const label = `${c.name ? `${c.name}: ` : ''}${entries[0]?.entry.kind ?? c.constraintType}`
    for (const e of entries) {
      if (e.check) tableById.get(e.check.tableId).checks.push({ name: entries.length === 1 ? c.name || null : null, text: e.check.text })
      else if (e.query) queries.push({ label: e.entry.kind === entries[0].entry.kind ? label : `${label}, ${e.entry.kind}`, name: c.name || null, kind: e.entry.kind, ...e })
    }
    const bad = entries.filter(e => !e.check && !e.query)
    if (bad.length) unwrittenNotes.push(`${model.notExported[i]}: ${bad.map(e => e.error).join('; ')}`)
  })
  for (const f of notColumns) warnings.push(`Fact type ${(f.readingParts ?? []).join(' ').trim() || f.id} is not a column and is not exported`)
  for (const t of tables) for (const col of t.columns)
    if (!col.singleValued) warnings.push(`${t.name}.${col.name} has no uniqueness constraint on the table's role; it is exported as an ordinary column`)

  const q = quoteIdent
  let ctxCache = null
  const sideCtx = () => (ctxCache ??= sideContext(state, schemaId))
  const lines = ['-- PostgreSQL DDL written by FreeFBM', '']
  // Tables with rules: views (viewSql.js), over a stored <name>_base when
  // some of their rows or columns are stored.
  const views = tableViews(state, model, typeSql)
  const storedName = (t) => { const v = views.get(t.id); return v?.kind === 'base' ? v.baseName : t.name }
  for (const t of tables) {
    const view = views.get(t.id)
    // Rules with no SQL form yet: the table is written, with its rules as comments.
    if (view?.kind === 'table') {
      for (const r of tableRulesOf(t.entity)) {
        const ctx = sideCtx()
        const text = `${tokensText(sideTokens(tableRuleAsMapping(t.entity, r).rule.target, ctx))} ${r.mode === 'semiDerived' ? '⟸' : '⟺'} ${tokensText(sideTokens(r.body, ctx))}`
        lines.push(`-- ${r.kind === 'table' ? 'Rows' : 'Columns'} ${r.mode === 'semiDerived' ? 'semi-derived' : 'derived'} by: ${text.replace(/\s+/g, ' ')}`)
      }
      warnings.push(`${t.name}: its table rules are written as comments, not as a view (${view.error})`)
    }
    if (view?.kind === 'view') {
      if (t.uniques.length || t.checks.length) warnings.push(`${t.name} is a view: its UNIQUE and CHECK constraints are not enforced`)
      continue
    }
    const skip = view?.kind === 'base' ? view.derivedCols : new Set()
    const items = []
    for (const col of t.columns) {
      if (skip.has(col.fact.id)) continue
      const role = col.fact.roles[col.v]
      let type = typeSql(col.vt.datatypeAssignment, col.generated)
      if (!type) { type = 'text'; warnings.push(`${t.name}.${col.name}: ${col.vt.name} has no PostgreSQL or SQL datatype; written as text`) }
      let line = `  ${q(col.name)} ${type}`
      if (col.notNull && !view?.semiCols?.has(col.fact.id)) line += ' NOT NULL'
      const numeric = NUMERIC_KINDS.has(valueKindName(col.vt.datatypeAssignment) ?? '')
      for (const specs of [col.vt.valueRange, role.valueRange]) {
        const cond = specs?.length ? rangeSql(q(col.name), specs, numeric) : null
        if (cond) line += ` CHECK (${cond})`
      }
      items.push(line)
    }
    // Keys keep the names the script gave them (relationalModel's nameKeys).
    const named = (n) => (n?.explicit ? `CONSTRAINT ${q(n.name)} ` : '')
    if (t.pk) items.push(`  ${named(t.pkName)}PRIMARY KEY (${t.pk.map(c => q(c.name)).join(', ')})`)
    const kept = (cols) => cols.every(c => !skip.has(c.fact.id))
    t.uniques.forEach((u, i) => { if (kept(u)) items.push(`  ${named(t.uniqueNames?.[i])}UNIQUE (${u.map(c => q(c.name)).join(', ')})`) })
    for (const ch of t.checks) items.push(`  ${ch.name ? `CONSTRAINT ${q(ch.name)} ` : ''}CHECK (${ch.text})`)
    if (!t.columns.length) warnings.push(`Table ${t.name} has no columns`)
    if (view?.kind === 'base') lines.push(`-- ${t.name} is a view (below) over its stored part ${storedName(t)}.`)
    lines.push(`CREATE TABLE ${q(storedName(t))} (`, items.join(',\n'), ');', '')
  }
  // Foreign keys between stored columns; a view's are not enforced.
  const isStored = (t, cols) => views.get(t.id)?.kind !== 'view' && cols.every(c => !views.get(t.id)?.derivedCols?.has(c.fact.id))
  const storedFks = fks.filter(fk => isStored(fk.fromTable, fk.from) && isStored(fk.toTable, fk.to))
  for (const fk of fks) if (!storedFks.includes(fk)) warnings.push(`FOREIGN KEY ${fk.fromTable.name}(${fk.from.map(c => c.name).join(', ')}) → ${fk.toTable.name}(${fk.to.map(c => c.name).join(', ')}) is about a view or a derived column and is not enforced`)
  for (const fk of storedFks) {
    lines.push(`ALTER TABLE ${q(storedName(fk.fromTable))} ADD ${fk.name?.explicit ? `CONSTRAINT ${q(fk.name.name)} ` : ''}FOREIGN KEY (${fk.from.map(c => q(c.name)).join(', ')})`
      + ` REFERENCES ${q(storedName(fk.toTable))} (${fk.to.map(c => q(c.name)).join(', ')});`)
  }
  if (storedFks.length) lines.push('')
  const order = viewOrder(views)
  if (order.length) {
    lines.push('-- Tables with derived rows or columns (table rules), as views:', '')
    for (const id of order) lines.push(views.get(id).view, '')
  }
  // Assertions: constraint triggers (enforced) or commented queries.
  const triggers = [], commented = []
  for (const x of queries) {
    if (assertionMode !== 'triggers' || x.deontic) { commented.push(x); continue }
    // Triggers go on the stored tables the query reads; a view has none.
    const on = [...new Set((x.tables ?? []).map(id => tableById.get(id)).filter(t => t && views.get(t.id)?.kind !== 'view').map(storedName))]
    if (!on.length) { commented.push(x); warnings.push(`${x.label}: it reads only views, so it gets no trigger`); continue }
    triggers.push({ ...x, on, src: x })
  }
  if (triggers.length) {
    lines.push('-- Assertions, enforced by constraint triggers: each change of a table an',
      '-- assertion reads runs its check at the end of the transaction, which fails',
      '-- when the query finds a row breaking it.', '')
    const used = new Set(tables.map(t => t.name))
    const fresh = (base) => {
      let name = base.slice(0, 63)
      for (let i = 2; used.has(name); i++) name = `${base.slice(0, 60)}_${i}`
      used.add(name)
      return name
    }
    triggers.forEach((x, i) => {
      const base = snakeName(x.name) || `assertion_${i + 1}`
      const fn = fresh(`${base}_check`)
      const what = (x.name ? `${x.name} (${x.kind})` : x.kind).replace(/'/g, "''")
      lines.push(`-- ${x.label}`, `--   ${x.text}`,
        `CREATE FUNCTION ${q(fn)}() RETURNS trigger LANGUAGE plpgsql AS $fn$`,
        'BEGIN',
        '  IF EXISTS (',
        ...x.query.split('\n').map(l => `    ${l}`),
        '  ) THEN',
        `    RAISE EXCEPTION 'assertion ${what} is violated' USING ERRCODE = 'check_violation', DETAIL = '${String(x.text ?? '').replace(/'/g, "''")}';`,
        '  END IF;',
        '  RETURN NULL;',
        'END',
        '$fn$;')
      for (const t of x.on) {
        lines.push(`CREATE CONSTRAINT TRIGGER ${q(fresh(`${base}_on_${t}`))} AFTER INSERT OR UPDATE OR DELETE ON ${q(t)}`,
          `  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION ${q(fn)}();`)
      }
      lines.push('')
    })
  }
  if (commented.length) {
    lines.push('-- Constraints that PostgreSQL does not enforce here, as queries that return',
      '-- the rows breaking them (none when the data satisfies them):', '')
    for (const x of commented) {
      lines.push(`-- ${x.label}${x.deontic ? ' (deontic: ought to hold)' : ''}`, `--   ${x.text}`,
        ...`${x.query};`.split('\n').map(l => `-- ${l}`), '')
    }
  }
  const otById = new Map((state.objectTypes ?? []).map(o => [o.id, o]))
  const notes = [...unwrittenNotes]
  for (const s of (state.subtypes ?? []).filter(inSchema)) notes.push(`subtype ${otById.get(s.subId)?.name} of ${otById.get(s.superId)?.name}`)
  // Constraints of the schema that the export has no SQL for at all.
  for (const t of tables) for (const col of t.columns)
    if ((col.fact.internalFrequency ?? []).length) notes.push(`frequency constraint on ${t.name}.${col.name}`)
  for (const o of (state.objectTypes ?? []).filter(inSchema))
    if (o.cardinalityRange?.length) notes.push(`cardinality range of ${o.name}`)
  for (const t of tables) for (const col of t.columns)
    if (col.fact.roles.some(r => r.cardinalityRange?.length)) notes.push(`cardinality range on ${t.name}.${col.name}`)
  for (const n of notes) warnings.push(`Not exported: ${n}`)
  if (warnings.length) lines.push('-- Not written as SQL:', ...warnings.map(w => `--   ${w}`), '')
  return {
    sql: lines.join('\n'), warnings, queries: queries.length,
    // What PostgreSQL will not enforce, for the export report
    // (DdlExportDialog.jsx): assertions written as violation queries, and
    // the other warnings.
    assertions: queries.map(x => ({ label: x.label, text: x.text, deontic: !!x.deontic, trigger: triggers.some(t => t.src === x) })),
  }
}
