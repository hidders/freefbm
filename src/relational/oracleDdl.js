// Writes a relational schema as Oracle DDL (Oracle AI Database 23.26.1 or
// later; constraint enforcement, stage 2). The same reading of the schema as
// the PostgreSQL export (ddlExport.js), in Oracle's dialect (sqlNames.js
// withDialect): datatypes mapped to Oracle's, CHECKs written from their
// formulas (a CHECK read from a PostgreSQL script keeps PostgreSQL's text
// only in the PostgreSQL export), and assertions as planned by
// planEnforcement (enforcement.js):
//
//   assertion  CREATE ASSERTION … CHECK (NOT EXISTS (violation query)),
//              DEFERRABLE INITIALLY DEFERRED when it asks for rows (checked at
//              commit). Oracle decides whether it can check the joins fast;
//              when it refuses, the script falls back to the plan's choice
//              (triggers, or nothing with a message), in one PL/SQL block.
//   trigger    a statement trigger per table the query reads, AFTER INSERT
//              OR UPDATE OR DELETE, that raises an error when the query finds
//              a row. Oracle has no deferred triggers, so it checks after each
//              statement.
//   audit      the query as a comment.
//
// exportOracleDdl(state, schemaId, { assertions, overrides })
//   → { sql, warnings, queries, assertions, plan }

import { tableViews, viewOrder } from './viewSql.js'
import { valueKindName } from '../utils/datatypeValues.js'
import { relationalModel } from './relationalModel.js'
import { quoteIdent, withDialect } from './sqlNames.js'
import { constraintsAsSql } from './formulaSql.js'
import { rangeSql } from './ddlExport.js'
import { planEnforcement, sqlSettings } from './enforcement.js'
import { relationalView } from './relationalView.js'

const snakeName = (name) => String(name ?? '').trim().replace(/[^A-Za-z0-9]+/g, '_').replace(/^_+|_+$/g, '').toLowerCase()

// PostgreSQL datatypes in Oracle, and other profiles by their value kind.
// → { type, warning? } | null
export function oracleType(assignment, generated) {
  const identity = (t) => `${t} GENERATED BY DEFAULT AS IDENTITY`
  if (generated === 'serial' || generated === 'smallserial') return { type: identity('NUMBER(10)') }
  if (generated === 'bigserial') return { type: identity('NUMBER(19)') }
  if (!assignment?.datatypeId) return null
  const p = assignment.params ?? {}
  const id = assignment.datatypeId
  let type = null, warning = null
  if (assignment.profileId === 'postgresql') {
    const map = {
      smallint: 'NUMBER(5)', integer: 'NUMBER(10)', bigint: 'NUMBER(19)', smallserial: 'NUMBER(5)', serial: 'NUMBER(10)', bigserial: 'NUMBER(19)',
      real: 'BINARY_FLOAT', 'double precision': 'BINARY_DOUBLE', money: 'NUMBER(19, 2)',
      text: 'VARCHAR2(4000)', bytea: 'BLOB', boolean: 'BOOLEAN', date: 'DATE',
      uuid: 'VARCHAR2(36)', json: 'JSON', jsonb: 'JSON', xml: 'XMLTYPE',
      inet: 'VARCHAR2(45)', cidr: 'VARCHAR2(45)', macaddr: 'VARCHAR2(17)', macaddr8: 'VARCHAR2(23)',
    }
    if (id === 'numeric') type = p.precision != null ? `NUMBER(${p.precision}${p.scale != null ? `, ${p.scale}` : ''})` : 'NUMBER'
    else if (id === 'character varying') type = `VARCHAR2(${p.length ?? 4000} CHAR)`
    else if (id === 'character') type = `CHAR(${p.length ?? 1} CHAR)`
    else if (id === 'timestamp') type = `TIMESTAMP${p.precision != null ? `(${p.precision})` : ''}${p.withTimeZone ? ' WITH TIME ZONE' : ''}`
    else if (id === 'time') { type = 'VARCHAR2(18)'; warning = 'Oracle has no time type; written as VARCHAR2(18)' }
    else if (id === 'interval') type = /^\s*(YEAR|MONTH)/i.test(p.fields ?? '') ? 'INTERVAL YEAR TO MONTH' : 'INTERVAL DAY TO SECOND'
    else if (map[id]) type = map[id]
    else { type = 'VARCHAR2(4000)'; warning = `Oracle has no ${id === 'user-defined' ? p.sql || 'user-defined' : id} type; written as VARCHAR2(4000)` }
  } else {
    const byKind = { integer: 'NUMBER(19)', decimal: 'NUMBER', float: 'BINARY_DOUBLE', boolean: 'BOOLEAN', date: 'DATE',
      datetime: 'TIMESTAMP', string: 'VARCHAR2(4000)', hexBinary: 'BLOB', yearMonthDuration: 'INTERVAL YEAR TO MONTH', dayTimeDuration: 'INTERVAL DAY TO SECOND' }
    type = byKind[valueKindName(assignment)] ?? null
    if (!type) return null
  }
  if (generated === 'identity') type = identity(type)
  return { type, warning }
}

// A literal of a value range in Oracle: dates and timestamps need their
// keyword (a plain string would go through NLS_DATE_FORMAT).
const literalFor = (kind) => (v) => {
  const s = String(v).trim()
  if ((kind === 'integer' || kind === 'decimal' || kind === 'float') && /^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(s)) return s
  if (kind === 'date') return `DATE '${s.replace(/'/g, "''")}'`
  if (kind === 'datetime') return `TIMESTAMP '${s.replace('T', ' ').replace(/'/g, "''")}'`
  if (kind === 'boolean' && /^(true|false)$/i.test(s)) return s.toUpperCase()
  return `'${String(v).replace(/'/g, "''")}'`
}

// q'X…X' quoting for dynamic SQL: a delimiter the text doesn't close early.
const qQuote = (text) => {
  const d = [['~', '~'], ['!', '!'], ['#', '#'], ['^', '^'], ['|', '|'], ['[', ']'], ['{', '}']]
    .find(([, c]) => !text.includes(`${c}'`)) ?? ['~', '~']
  return `q'${d[0]}${text}${d[1]}'`
}

export function exportOracleDdl(state, schemaId, options = {}) {
  // The relational view (cached, PostgreSQL text) before switching dialects.
  relationalView(state, schemaId)
  const own = sqlSettings((state.schemas ?? []).find(x => x.id === schemaId))
  const settings = { ...own, target: 'oracle',
    ...(options.assertions && { assertions: options.assertions === 'triggers' ? 'triggers' : 'audit' }),
    ...(options.overrides && { overrides: options.overrides }) }
  const plan = planEnforcement(state, schemaId, settings)
  return withDialect('oracle', () => write(state, schemaId, plan))
}

function write(state, schemaId, plan) {
  const q = quoteIdent
  const inSchema = (x) => !schemaId || x.schemaId === schemaId
  const model = relationalModel(state, schemaId)
  const { tables, fks, notColumns } = model
  const warnings = []
  const tableById = new Map(tables.map(t => [t.id, t]))
  const typeOf = (a, g) => oracleType(a, g)?.type ?? null
  const unwrittenNotes = []
  constraintsAsSql(state, model).forEach(({ c, entries }, i) => {
    for (const e of entries)
      if (e.check) tableById.get(e.check.tableId).checks.push({ name: entries.length === 1 ? c.name || null : null, text: e.check.text })
    const bad = entries.filter(e => !e.check && !e.query)
    if (bad.length) unwrittenNotes.push(`${model.notExported[i]}: ${bad.map(e => e.error).join('; ')}`)
  })
  for (const f of notColumns) warnings.push(`Fact type ${(f.readingParts ?? []).join(' ').trim() || f.id} is not a column and is not exported`)
  for (const t of tables) for (const col of t.columns)
    if (!col.singleValued) warnings.push(`${t.name}.${col.name} has no uniqueness constraint on the table's role; it is exported as an ordinary column`)

  const planned = plan.items.filter(x => x.kind === 'assertion' && x.entry?.query)
  const queries = planned.map(x => ({ ...x.entry, technique: x.technique, viewsOnly: !!x.viewsOnly }))
  const badFks = new Set(planned.filter(x => x.rmId.startsWith('fk:')).map(x => x.entry.constraintId))

  const lines = ['-- Oracle DDL (23.26.1 or later) written by FreeFBM', '-- Run it in SQL*Plus or SQLcl: PL/SQL blocks end with a line holding /.', '']
  const views = tableViews(state, model, typeOf)
  const storedName = (t) => { const v = views.get(t.id); return v?.kind === 'base' ? v.baseName : t.name }
  for (const t of tables) {
    const view = views.get(t.id)
    if (view?.kind === 'table') warnings.push(`${t.name}: its table rules are not written as a view (${view.error})`)
    if (view?.kind === 'view') {
      if (t.uniques.length || t.checks.length) warnings.push(`${t.name} is a view: its UNIQUE and CHECK constraints are not enforced`)
      continue
    }
    const skip = view?.kind === 'base' ? view.derivedCols : new Set()
    const items = []
    for (const col of t.columns) {
      if (skip.has(col.fact.id)) continue
      const role = col.fact.roles[col.v]
      const ty = oracleType(col.vt.datatypeAssignment, col.generated)
      if (ty?.warning) warnings.push(`${t.name}.${col.name}: ${ty.warning}`)
      let type = ty?.type
      if (!type) { type = 'VARCHAR2(4000)'; warnings.push(`${t.name}.${col.name}: ${col.vt.name} has no datatype Oracle knows; written as VARCHAR2(4000)`) }
      let line = `  ${q(col.name)} ${type}`
      if (col.notNull && !view?.semiCols?.has(col.fact.id)) line += ' NOT NULL'
      const kind = valueKindName(col.vt.datatypeAssignment) ?? ''
      for (const specs of [col.vt.valueRange, role.valueRange]) {
        const cond = specs?.length ? rangeSql(q(col.name), specs, false, literalFor(kind)) : null
        if (cond) line += ` CHECK (${cond})`
      }
      items.push(line)
    }
    const named = (n) => (n?.explicit ? `CONSTRAINT ${q(n.name)} ` : '')
    if (t.pk) items.push(`  ${named(t.pkName)}PRIMARY KEY (${t.pk.map(c => q(c.name)).join(', ')})`)
    const kept = (cols) => cols.every(c => !skip.has(c.fact.id))
    t.uniques.forEach((u, i) => { if (kept(u)) items.push(`  ${named(t.uniqueNames?.[i])}UNIQUE (${u.map(c => q(c.name)).join(', ')})`) })
    for (const ch of t.checks) items.push(`  ${ch.name ? `CONSTRAINT ${q(ch.name)} ` : ''}CHECK (${ch.text})`)
    if (!t.columns.length) warnings.push(`Table ${t.name} has no columns`)
    if (view?.kind === 'base') lines.push(`-- ${t.name} is a view (below) over its stored part ${storedName(t)}.`)
    lines.push(`CREATE TABLE ${q(storedName(t))} (`, items.join(',\n'), ');', '')
  }
  const isStored = (t, cols) => views.get(t.id)?.kind !== 'view' && cols.every(c => !views.get(t.id)?.derivedCols?.has(c.fact.id))
  const storedFks = fks.filter(fk => !badFks.has(fk.constraintId) && isStored(fk.fromTable, fk.from) && isStored(fk.toTable, fk.to))
  for (const fk of fks) if (!storedFks.includes(fk) && !badFks.has(fk.constraintId))
    warnings.push(`FOREIGN KEY ${fk.fromTable.name}(${fk.from.map(c => c.name).join(', ')}) → ${fk.toTable.name}(${fk.to.map(c => c.name).join(', ')}) is about a view or a derived column and is not enforced`)
  for (const fk of storedFks) {
    lines.push(`ALTER TABLE ${q(storedName(fk.fromTable))} ADD ${fk.name?.explicit ? `CONSTRAINT ${q(fk.name.name)} ` : ''}FOREIGN KEY (${fk.from.map(c => q(c.name)).join(', ')})`
      + ` REFERENCES ${q(storedName(fk.toTable))} (${fk.to.map(c => q(c.name)).join(', ')});`)
  }
  if (storedFks.length) lines.push('')
  const cols = (cs) => cs.map(c => q(c.name)).join(', ')
  const asFks = queries.filter(x => x.technique === 'foreignKey' && !x.fk.existing)
  if (asFks.length) lines.push('-- Assertions that are foreign keys:', '')
  for (const x of asFks) {
    const { fk } = x
    lines.push(`-- ${x.label}`, `--   ${x.text}`)
    if (fk.addUnique) lines.push(`ALTER TABLE ${q(storedName(fk.toTable))} ADD UNIQUE (${cols(fk.to)});`)
    lines.push(`ALTER TABLE ${q(storedName(fk.fromTable))} ADD ${x.name ? `CONSTRAINT ${q(snakeName(x.name).slice(0, 128))} ` : ''}FOREIGN KEY (${cols(fk.from)})`
      + ` REFERENCES ${q(storedName(fk.toTable))} (${cols(fk.to)});`, '')
  }
  const order = viewOrder(views)
  if (order.length) {
    lines.push('-- Tables with derived rows or columns (table rules), as views:', '')
    for (const id of order) lines.push(views.get(id).view, '')
  }

  // Assertions, triggers and audit queries.
  const used = new Set(tables.map(t => t.name))
  const fresh = (base) => {
    let name = base.slice(0, 128)
    for (let i = 2; used.has(name); i++) name = `${base.slice(0, 124)}_${i}`
    used.add(name)
    return name
  }
  const indent = (text, pad) => text.split('\n').map(l => `${pad}${l}`)
  const triggerSql = (x, base, table) => {
    const what = (x.name ? `${x.name} (${x.kind})` : x.kind).replace(/'/g, "''").slice(0, 1800)
    return [`CREATE OR REPLACE TRIGGER ${q(fresh(`${base}_on_${table}`))}`,
      `  AFTER INSERT OR UPDATE OR DELETE ON ${q(table)}`,
      'DECLARE', '  violated NUMBER;', 'BEGIN',
      '  SELECT COUNT(*) INTO violated FROM dual WHERE EXISTS (',
      ...indent(x.query, '    '),
      '  );',
      `  IF violated > 0 THEN RAISE_APPLICATION_ERROR(-20001, 'assertion ${what} is violated'); END IF;`,
      'END;'].join('\n')
  }
  const onTables = (x) => [...new Set((x.tables ?? []).map(id => tableById.get(id)).filter(t => t && views.get(t.id)?.kind !== 'view').map(storedName))]
  const asserted = queries.filter(x => x.technique === 'assertion')
  const triggered = queries.filter(x => x.technique === 'trigger')
  const commented = queries.filter(x => x.technique === 'audit')
  if (asserted.length) {
    lines.push('-- Assertions (CREATE ASSERTION). Oracle checks one at commit when it is',
      '-- DEFERRABLE INITIALLY DEFERRED, else after each statement. When Oracle',
      '-- cannot check an assertion\'s joins fast it refuses it (ORA-08689); the',
      '-- block then creates triggers instead, or says it left the assertion out.', '')
    asserted.forEach((x, i) => {
      const base = snakeName(x.name) || `assertion_${i + 1}`
      const name = fresh(base)
      const create = `CREATE ASSERTION ${q(name)} CHECK (NOT EXISTS (\n${x.oracle.body}\n))${x.mustHave ? ' DEFERRABLE INITIALLY DEFERRED' : ''}`
      const on = onTables(x)
      const fallback = x.fallback === 'trigger' && on.length
        ? on.map(t => `    EXECUTE IMMEDIATE ${qQuote(triggerSql(x, base, t))};`)
        : []
      lines.push(`-- ${x.label}`, `--   ${x.text}`, 'BEGIN',
        `  EXECUTE IMMEDIATE ${qQuote(create)};`,
        'EXCEPTION WHEN OTHERS THEN',
        `  DBMS_OUTPUT.PUT_LINE('${name.replace(/'/g, "''")}: ' || SQLERRM);`,
        ...(fallback.length
          ? ['  BEGIN', ...fallback, `    DBMS_OUTPUT.PUT_LINE('${name.replace(/'/g, "''")}: enforced by triggers instead');`, '  END;']
          : [`  DBMS_OUTPUT.PUT_LINE('${name.replace(/'/g, "''")}: not enforced (its query is in the export as a comment)');`]),
        'END;', '/', '')
      if (!fallback.length) commented.push({ ...x, fallbackOnly: true })
    })
  }
  if (triggered.length) {
    lines.push('-- Assertions Oracle cannot assert, enforced by triggers: each statement that',
      '-- changes a table an assertion reads runs its query and fails when it finds a',
      '-- row breaking it. Oracle has no deferred triggers, so the check is after each',
      '-- statement: insert rows in an order that keeps it true.', '')
    triggered.forEach((x, i) => {
      const base = snakeName(x.name) || `assertion_t${i + 1}`
      lines.push(`-- ${x.label}`, `--   ${x.text}`)
      for (const t of onTables(x)) lines.push(triggerSql(x, base, t), '/')
      lines.push('')
    })
  }
  if (commented.length) {
    lines.push('-- Constraints that Oracle does not enforce here (or, marked "if refused",',
      '-- only when it refuses the assertion above), as queries that return the rows',
      '-- breaking them (none when the data satisfies them):', '')
    for (const x of commented) {
      lines.push(`-- ${x.label}${x.deontic ? ' (deontic: ought to hold)' : ''}${x.fallbackOnly ? ' (if refused)' : ''}`, `--   ${x.text}`,
        ...`${x.query};`.split('\n').map(l => `-- ${l}`), '')
      if (x.viewsOnly) warnings.push(`${x.label}: it reads only views, so it gets no trigger`)
    }
  }
  const otById = new Map((state.objectTypes ?? []).map(o => [o.id, o]))
  const notes = [...unwrittenNotes]
  for (const s of (state.subtypes ?? []).filter(inSchema)) notes.push(`subtype ${otById.get(s.subId)?.name} of ${otById.get(s.superId)?.name}`)
  for (const t of tables) for (const col of t.columns)
    if ((col.fact.internalFrequency ?? []).length) notes.push(`frequency constraint on ${t.name}.${col.name}`)
  for (const o of (state.objectTypes ?? []).filter(inSchema))
    if (o.cardinalityRange?.length) notes.push(`cardinality range of ${o.name}`)
  for (const t of tables) for (const col of t.columns)
    if (col.fact.roles.some(r => r.cardinalityRange?.length)) notes.push(`cardinality range on ${t.name}.${col.name}`)
  for (const n of notes) warnings.push(`Not exported: ${n}`)
  if (warnings.length) lines.push('-- Not written as SQL:', ...warnings.map(w => `--   ${w}`), '')
  return {
    sql: lines.join('\n'), warnings, queries: queries.length, plan,
    assertions: queries.map(x => ({ label: x.label, text: x.text, deontic: !!x.deontic, technique: x.technique })),
  }
}
