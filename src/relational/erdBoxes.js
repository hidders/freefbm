// Where an ERD draws its tables (ErdView.jsx), and where an element of the
// relational schema is in it: the table box, or the row of a column.
//
// The ERD draws its tables from relationalModel, at diagram.erdPositions
// (top-left corners) or, for tables without one, laid out in columns by
// foreign key depth (layeredLayout). Panels that point at an element (the
// Validation panel's navigation, the validation badges, the minimap, the
// mapping layer) work with the same boxes, so they are computed here and not
// in the component. The occurrences of the elements in the diagram keep their
// ORM2 positions, which the ERD doesn't use.

import { inDiag, mappingOfDiagram, isViewMapping } from '../store/storeHelpers.js'
import { isRelationalFace } from './face.js'
import { relationalModel } from './relationalModel.js'
import { relationalView, rmObjectOf } from './relationalView.js'
import { typeSql } from './ddlExport.js'
import { layeredLayout } from './erdRouting.js'
import { DIAGRAM_FONT, measureDiagramText } from '../diagram/diagramFont.js'

export const FONT = DIAGRAM_FONT
export const HEAD_H = 24, ROW_H = 19, PAD_X = 8, MARK_GAP = 6, GAP_TYPE = 18, MIN_W = 140
const GAP_Y = 70

// Whether the diagram is drawn as an ERD: its schema is relational and shows
// its relational face (relational/face.js: not its logical view).
export function isErdDiagram(state, diagram) {
  if (!diagram || diagram.mappingId) return false   // mapping diagrams are drawn in ORM2
  return isRelationalFace(state, diagram.schemaId)
}

function measure(text, size, weight = 400) {
  return measureDiagramText(text, size, weight)
}

export function columnType(col) {
  const t = typeSql(col.vt.datatypeAssignment, col.generated)
  if (!t) return col.vt.name
  return t.replace(' generated by default as identity', ' identity')
}

export function columnMarks(col) {
  return [col.pk && 'PK', col.fk && 'FK', !col.pk && col.unique && 'U'].filter(Boolean).join(' ')
}

// Box sizes, and positions for tables that have none stored: columns by
// foreign key depth, referenced tables left (see layeredLayout).
export function erdLayout(model, diagram, origin = null) {
  const shown = model.tables.filter(t => inDiag(diagram, t.id))
  const boxes = new Map()
  for (const t of shown) {
    // Width of the PK/FK/U column: the widest marks in this table.
    const markW = Math.max(16, ...t.columns.map(c => measure(columnMarks(c), 9, 700))) + MARK_GAP
    let w = measure(t.name, 13, 700) + PAD_X * 2
    for (const c of t.columns)
      w = Math.max(w, markW + measure(c.name, 12, c.notNull ? 600 : 400) + GAP_TYPE + measure(columnType(c), 11) + PAD_X * 2)
    boxes.set(t.id, { table: t, markW, w: Math.ceil(Math.max(MIN_W, w)), h: HEAD_H + Math.max(1, t.columns.length) * ROW_H + 6 })
  }
  const stored = diagram.erdPositions ?? {}
  const missing = shown.filter(t => !stored[t.id])
  let originY = 0
  for (const t of shown) {
    const p = stored[t.id]
    if (p) { boxes.get(t.id).x = p.x; boxes.get(t.id).y = p.y; originY = Math.max(originY, p.y + boxes.get(t.id).h + GAP_Y) }
  }
  if (missing.length) {
    const edges = model.fks.map(fk => [fk.fromTable.id, fk.toTable.id])
    layeredLayout(boxes, missing.map(t => t.id), edges, origin && !Object.keys(stored).some(id => boxes.has(id)) ? origin.y : originY)
    // In a mapping diagram, where that side's elements were.
    if (origin) for (const t of missing) boxes.get(t.id).x += origin.x
  }
  return boxes
}

// The table boxes of a relational schema in a mapping diagram: laid out from
// where the schema's elements are (the top-left of their occurrences).
export function mappingErdBoxes(state, diagram, schemaId) {
  const model = relationalModel(state, schemaId)
  const ids = new Set([...state.objectTypes, ...state.facts].filter(x => x.schemaId === schemaId).map(x => x.id))
  const occs = (diagram.occurrences ?? []).filter(o => ids.has(o.schemaElementId))
  const origin = occs.length ? { x: Math.min(...occs.map(o => o.x)) - 60, y: Math.min(...occs.map(o => o.y)) - 20 } : { x: 0, y: 0 }
  return { model, boxes: erdLayout(model, diagram, origin) }
}

// The relational schemas a diagram draws as ERD tables, each with its model
// and boxes: the diagram's own schema when it is an ERD, the relational sides
// of a mapping diagram that show their relational face (face.js
// erdSchemasOfDiagram), else none.
export function erdPartsOfDiagram(state, diagram) {
  if (!diagram) return []
  if (isErdDiagram(state, diagram)) {
    const model = relationalModel(state, diagram.schemaId)
    return [{ schemaId: diagram.schemaId, model, boxes: erdLayout(model, diagram) }]
  }
  const m = mappingOfDiagram(state, diagram)
  if (!m || isViewMapping(state, m)) return []
  return [...new Set([m.sourceSchemaId, m.targetSchemaId])]
    .filter(sid => isRelationalFace(state, sid))
    .map(sid => ({ schemaId: sid, ...mappingErdBoxes(state, diagram, sid) }))
}

// The column fact type ids an element of a relational schema is about, in
// the order it names them (for a constraint, the columns of its role
// sequences), so a target falls on a row.
function columnFactsOf(state, id) {
  const c = state.constraints?.find(x => x.id === id)
  if (!c) return []
  const out = []
  const walk = (v) => {
    if (Array.isArray(v)) v.forEach(walk)
    else if (v && typeof v === 'object') { if (typeof v.factId === 'string') out.push(v.factId); Object.values(v).forEach(walk) }
  }
  walk(c.sequences ?? c.roleSequences ?? [])
  walk(c.rule ?? null)
  return out
}

// Where an element (an ORM2 id of a relational schema: a table's entity type,
// a column's fact type, a value type, a key, a foreign key, a CHECK, an
// internal uniqueness or mandatory id) is drawn in the ERD parts of a diagram:
// { schemaId, tableId, factId (the column's row, or null), x, y, w, h } in
// diagram coordinates, or null when the diagram doesn't draw it.
export function erdTargetOf(state, parts, id) {
  if (!id) return null
  const rowOf = (part, box, factId) => {
    const i = box.table.columns.findIndex(c => c.fact.id === factId)
    if (i < 0) return null
    return { schemaId: part.schemaId, tableId: box.table.id, factId, x: box.x, y: box.y + HEAD_H + 3 + i * ROW_H, w: box.w, h: ROW_H }
  }
  const boxOf = (part, box) => ({ schemaId: part.schemaId, tableId: box.table.id, factId: null, x: box.x, y: box.y, w: box.w, h: box.h })
  const findRow = (factId) => {
    for (const part of parts) {
      const t = part.model.columnByFact?.get(factId)?.table
      const box = t && part.boxes.get(t.id)
      if (box) return rowOf(part, box, factId)
    }
    return null
  }
  for (const part of parts) {
    // A table.
    const box = part.boxes.get(id)
    if (box) return boxOf(part, box)
  }
  // A column.
  const row = findRow(id)
  if (row) return row
  for (const part of parts) {
    // A value type: the first shown column of that type.
    for (const box of part.boxes.values()) {
      const c = box.table.columns.find(col => col.vt?.id === id)
      if (c) return rowOf(part, box, c.fact.id)
    }
  }
  for (const part of parts) {
    // A key, foreign key, CHECK, NOT NULL: its first column, else its table.
    const view = relationalView(state, part.schemaId)
    const obj = rmObjectOf(view, id)
    if (!obj) continue
    const colRm = obj.kind === 'column' ? obj.rmId : obj.columns?.[0]
    const factId = colRm ? colRm.split(':').slice(1).join(':') : null
    const r = factId && findRow(factId)
    if (r) return r
    const tableObj = obj.table ? view.objects.get(obj.table) : (obj.kind === 'table' || obj.kind === 'view') ? obj : null
    const entityId = tableObj?.entityId ?? (tableObj?.of ? view.objects.get(tableObj.of)?.entityId : null)
    const tb = entityId && part.boxes.get(entityId)
    if (tb) return boxOf(part, tb)
  }
  // An assertion or another constraint: the first column it names.
  for (const factId of columnFactsOf(state, id)) {
    const r = findRow(factId)
    if (r) return r
  }
  return null
}
